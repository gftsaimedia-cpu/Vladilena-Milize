CREATE FUNCTION pay_entries_frozen_update_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.status = 'approved' AND (NEW.amount IS DISTINCT FROM OLD.amount OR NEW.direction IS DISTINCT FROM OLD.direction
      OR NEW.tax_mode IS DISTINCT FROM OLD.tax_mode OR NEW.tax_cap IS DISTINCT FROM OLD.tax_cap
      OR NEW.insurance_base IS DISTINCT FROM OLD.insurance_base OR NEW.username IS DISTINCT FROM OLD.username OR NEW.month IS DISTINCT FROM OLD.month) THEN
    RAISE EXCEPTION '%', 'khoản điền thêm đã duyệt không được sửa số tiền, hướng, thuế, bảo hiểm, người hay tháng' USING ERRCODE = 'integrity_constraint_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER pay_entries_frozen_update BEFORE UPDATE ON pay_entries FOR EACH ROW EXECUTE FUNCTION pay_entries_frozen_update_fn();

CREATE FUNCTION pay_entries_guard_update_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.created_by IS DISTINCT FROM OLD.created_by OR NEW.created_at IS DISTINCT FROM OLD.created_at
      OR (OLD.status = 'void' AND NEW.status IS DISTINCT FROM 'void')
      OR (OLD.status = 'approved' AND NEW.status NOT IN ('approved','void')) THEN
    RAISE EXCEPTION '%', 'pay_entries: không đổi người lập, không mở lại khoản đã huỷ, không lùi khoản đã duyệt' USING ERRCODE = 'integrity_constraint_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER pay_entries_guard_update BEFORE UPDATE ON pay_entries FOR EACH ROW EXECUTE FUNCTION pay_entries_guard_update_fn();

