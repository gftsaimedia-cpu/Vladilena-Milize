CREATE TRIGGER pay_entries_no_delete BEFORE DELETE ON pay_entries FOR EACH ROW EXECUTE FUNCTION pay_entries_no_delete_fn();

CREATE FUNCTION payroll_runs_guard_update_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.month IS DISTINCT FROM OLD.month OR NEW.run_no IS DISTINCT FROM OLD.run_no OR NEW.engine_version IS DISTINCT FROM OLD.engine_version
      OR NEW.params_hash IS DISTINCT FROM OLD.params_hash OR NEW.params_rev IS DISTINCT FROM OLD.params_rev
      OR NEW.params_json IS DISTINCT FROM OLD.params_json OR NEW.switches_json IS DISTINCT FROM OLD.switches_json
      OR NEW.inputs_digest IS DISTINCT FROM OLD.inputs_digest OR NEW.created_by IS DISTINCT FROM OLD.created_by
      OR NEW.created_at IS DISTINCT FROM OLD.created_at
      OR NOT (NEW.status = OLD.status OR (OLD.status = 'draft' AND NEW.status IN ('final','superseded'))
              OR (OLD.status = 'final' AND NEW.status = 'superseded'))
