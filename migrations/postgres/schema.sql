-- Lược đồ PostgreSQL của hệ thống Lương Nhân Sự: toàn bộ bảng, chỉ mục, trigger và dữ liệu gieo sẵn, trong một file.
-- Chạy một lần trên DB trống. Đổi lược đồ thì sửa thẳng file này rồi dựng lại DB; không thêm file đánh số.
-- Số liệu tiền dùng BIGINT; id tự tăng dùng IDENTITY; UUID dùng UUID hoặc TEXT; các ràng buộc toàn vẹn bảo vệ qua PL/pgSQL triggers.

CREATE TABLE audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at TEXT NOT NULL,                       -- ISO UTC
    actor TEXT NOT NULL,                    -- username hoặc 'system'
    actor_roles TEXT,                       -- vai trò lúc làm (mảng JSON)
    action TEXT NOT NULL,                   -- 'param.set', 'request.decide', 'slip.override', 'period.lock'...
    entity_kind TEXT NOT NULL, entity_id TEXT NOT NULL,
    subject TEXT,                           -- người bị tác động
    month TEXT,
    before_json TEXT, after_json TEXT,      -- chỉ qua danh sách trường cho phép của lib/audit.js, không bao giờ chứa bí mật
    reason TEXT,
    sensitivity TEXT NOT NULL DEFAULT 'normal' CHECK (sensitivity IN ('normal','pay','pii')),
    request_id TEXT,                        -- mã yêu cầu HTTP, để nối nhiều dòng của một thao tác
    prev_hash TEXT NOT NULL, hash TEXT NOT NULL,
    subject_uuid TEXT, actor_uuid TEXT
);

CREATE TABLE benefit_types (
    code TEXT PRIMARY KEY CHECK (length(code) > 0),
    label TEXT
);

CREATE TABLE kpi_score_log (        -- nhật ký chỉ thêm dòng: mã không UPDATE hay DELETE
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username  TEXT NOT NULL,
    month     TEXT NOT NULL,
    field     TEXT NOT NULL,                         -- wework | user | peer | manager | self (điểm × 100) | amt (đồng)
    old_value DOUBLE PRECISION,
    new_value DOUBLE PRECISION,
    by        TEXT NOT NULL,
    at        TEXT NOT NULL,
    reason    TEXT
);

CREATE TABLE kpi_scores (           -- điểm 5 thành phần KPI, mỗi người mỗi tháng một dòng; null = chưa nhập
    username    TEXT NOT NULL,
    month       TEXT NOT NULL,                       -- 'YYYY-MM'
    wework BIGINT CHECK (wework IS NULL OR (wework >= 0 AND wework <= 10000)),                           -- Base Wework (điểm × 100)
    user_score BIGINT CHECK (user_score IS NULL OR (user_score >= 0 AND user_score <= 10000)),                       -- người dùng
    peer BIGINT CHECK (peer IS NULL OR (peer >= 0 AND peer <= 10000)),                             -- đồng nghiệp
    manager BIGINT CHECK (manager IS NULL OR (manager >= 0 AND manager <= 10000)),                          -- quản lý trực tiếp
    self_score BIGINT CHECK (self_score IS NULL OR (self_score >= 0 AND self_score <= 10000)),                       -- tự đánh giá
    created_by  TEXT NOT NULL,
    created_at  TEXT NOT NULL,
    updated_by  TEXT NOT NULL,
    updated_at  TEXT NOT NULL,
    kpi_proposed BIGINT CHECK (kpi_proposed IS NULL OR kpi_proposed >= 0), -- lương KPI đề xuất của tháng (VND); NULL = chưa nhập
    PRIMARY KEY (username, month)
);

CREATE TABLE param_versions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key             TEXT NOT NULL,
    effective_month TEXT NOT NULL CHECK (effective_month ~ '^[0-9]{4}-[0-1][0-9]$'),
    value_json      TEXT NOT NULL,          -- giá trị đã kiểm, JSON; Infinity lưu là null
    reason          TEXT NOT NULL CHECK (length(reason) BETWEEN 10 AND 300),
    basis           TEXT,                   -- căn cứ (số văn bản, điều khoản) Admin ghi
    ack_json        TEXT,                   -- các cảnh báo sàn luật đã xác nhận (mã + người xác nhận)
    created_by      TEXT NOT NULL,
    created_at      TEXT NOT NULL,
    batch_id        TEXT
);

CREATE TABLE pay_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL CHECK (length(username) > 0),
    month TEXT NOT NULL CHECK (month ~ '^[0-9]{4}-[0-1][0-9]$'),
    direction TEXT NOT NULL CHECK (direction IN ('add','deduct')),
    amount BIGINT NOT NULL CHECK (amount > 0),   -- VND đồng nguyên
    label TEXT NOT NULL CHECK (length(label) BETWEEN 1 AND 80),
    slip_line TEXT,                         -- dòng trên phiếu lương; null = dùng nhãn
    reason TEXT NOT NULL CHECK (length(reason) BETWEEN 10 AND 300),
    tax_mode TEXT CHECK (tax_mode IS NULL OR tax_mode IN ('none','full','cap')),
    tax_cap BIGINT CHECK (tax_cap IS NULL OR (tax_cap >= 0)),
    insurance_base BIGINT CHECK (insurance_base IS NULL OR (insurance_base >= 0)),
    flags_confirmed_by TEXT, flags_confirmed_at TEXT,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected','void')),
    rev BIGINT NOT NULL DEFAULT 1,
    created_by TEXT NOT NULL, created_at TEXT NOT NULL,
    decided_by TEXT, decided_at TEXT, decision_note TEXT
);

CREATE TABLE payroll_periods (
    month TEXT PRIMARY KEY,
    status TEXT NOT NULL CHECK (status IN ('open','attendance_locked','calculated','reviewed','approved','paid')),
    rev BIGINT NOT NULL DEFAULT 1,
    current_run_id BIGINT,
    attendance_locked_by TEXT, attendance_locked_at TEXT,
    calculated_by TEXT, calculated_at TEXT,
    reviewed_by TEXT, reviewed_at TEXT,
    approved_by TEXT, approved_at TEXT,
    paid_by TEXT, paid_at TEXT, paid_ref TEXT,
    reopen_count BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE payroll_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    month TEXT NOT NULL,
    run_no BIGINT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('draft','final','superseded')),
    engine_version TEXT NOT NULL,
    params_hash TEXT NOT NULL, params_rev BIGINT NOT NULL, params_json TEXT NOT NULL,
    switches_json TEXT NOT NULL,            -- ngày lễ của tháng
    inputs_digest TEXT,                     -- băm chuẩn hoá đầu vào đã dùng
    slips_total BIGINT, slips_error BIGINT,
    created_by TEXT NOT NULL, created_at TEXT NOT NULL, finished_at TEXT,
    UNIQUE (month, run_no)
);

CREATE TABLE payslips (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES payroll_runs(id),
    username TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('draft','pending','approved','error')),
    rev BIGINT NOT NULL DEFAULT 1,
    error_code TEXT, error_detail TEXT,
    gross BIGINT, insurance BIGINT, tax BIGINT, advance BIGINT, net BIGINT,   -- đồng nguyên, sau làm tròn của calcNet và số sửa
    staff_terms_json TEXT NOT NULL,         -- loại, level, base, hợp đồng, BH, người phụ thuộc, iDorm... đúng lúc tính
    snapshot_gz BYTEA NOT NULL,              -- gzip(JSON(m)), gồm rows (zlib có sẵn của Node)
    override_json TEXT,                     -- số sửa đóng băng lúc duyệt kỳ (kèm lý do)
    flags_json TEXT,                        -- mã phát hiện AI còn mở hoặc đã bỏ qua khi tính (mảng); không rỗng thì không vào duyệt cả lô
    decided_by TEXT, decided_at TEXT, note TEXT,
    UNIQUE (run_id, username)
);

CREATE TABLE position_levels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_code TEXT NOT NULL CHECK (length(type_code) > 0),
    level_no BIGINT NOT NULL CHECK (level_no >= 1),
    effective_month TEXT NOT NULL CHECK (effective_month ~ '^[0-9]{4}-[0-1][0-9]$'),
    name TEXT NOT NULL CHECK (length(name) > 0),
    base_salary BIGINT NOT NULL CHECK (base_salary >= 0),  -- VND đồng nguyên
    kpi_max BIGINT CHECK (kpi_max IS NULL OR (kpi_max >= 0)),  -- NULL = không có lương KPI
    night_pct DOUBLE PRECISION CHECK (night_pct IS NULL OR night_pct BETWEEN 0 AND 100),                     -- NULL = theo chức vụ
    reason TEXT,
    updated_by TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    rev BIGINT NOT NULL DEFAULT 0,
    UNIQUE (type_code, level_no, effective_month)
);

CREATE TABLE position_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL CHECK (length(code) > 0),
    effective_month TEXT NOT NULL CHECK (effective_month ~ '^[0-9]{4}-[0-1][0-9]$'),
    name TEXT NOT NULL CHECK (length(name) > 0),
    workdays BIGINT NOT NULL CHECK (workdays BETWEEN 1 AND 31),   -- ngày công chuẩn, mẫu số lương ngày
    flex_pct DOUBLE PRECISION NOT NULL CHECK (flex_pct BETWEEN 0 AND 100),                                              -- phụ cấp ca Flex, % lương ngày
    night_pct DOUBLE PRECISION NOT NULL CHECK (night_pct BETWEEN 0 AND 100),                                             -- phụ cấp ca Night mặc định của chức vụ, %
    travel_pct DOUBLE PRECISION NOT NULL CHECK (travel_pct BETWEEN 0 AND 100),                                            -- phụ cấp đi lại, %
    attendance_pct DOUBLE PRECISION NOT NULL CHECK (attendance_pct BETWEEN 0 AND 100),                                        -- phụ cấp chuyên cần, %
    regular_dows TEXT NOT NULL CHECK ((regular_dows::jsonb IS NOT NULL)),     -- thứ đi làm: mảng JSON, 0 = Chủ nhật … 6 = thứ Bảy
    makeup_dows TEXT NOT NULL CHECK ((makeup_dows::jsonb IS NOT NULL)),       -- thứ chỉ làm bù / nghỉ không lương
    reason TEXT,
    updated_by TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    rev BIGINT NOT NULL DEFAULT 0,
    UNIQUE (code, effective_month)
);

