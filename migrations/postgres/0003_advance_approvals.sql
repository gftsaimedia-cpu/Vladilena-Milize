-- Yêu cầu ứng lương đang hoạt động: một phiên bản cho tháng và một dòng cho từng người đã từng yêu cầu.
-- Không có dữ liệu cũ cần chuyển. Nếu thực tế có tài liệu cũ, dừng thay vì âm thầm bỏ qua dữ liệu đó.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM settings WHERE left(key, length('advance_approvals_')) = 'advance_approvals_') THEN
    RAISE EXCEPTION 'SCHEMA_INCOMPATIBLE: Có dữ liệu tạm ứng cũ; hãy dùng database mới trống.';
  END IF;
END $$;

CREATE TABLE advance_approval_months (
  month TEXT PRIMARY KEY CHECK (month ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  rev BIGINT NOT NULL DEFAULT 0 CHECK (rev >= 0)
);

CREATE TABLE advance_approval_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  month TEXT NOT NULL REFERENCES advance_approval_months(month),
  username TEXT NOT NULL REFERENCES staff(username),
  status TEXT CHECK (status IN ('pending', 'approved', 'rejected')),
  rev BIGINT NOT NULL CHECK (rev > 0),
  requested_at TIMESTAMPTZ NOT NULL,
  requested_by TEXT NOT NULL CHECK (length(requested_by) > 0),
  decided_at TIMESTAMPTZ,
  decided_by TEXT,
  reason TEXT CHECK (reason IS NULL OR length(reason) <= 300),
  UNIQUE (month, username),
  CHECK (status IS NULL OR status = 'pending' OR (decided_at IS NOT NULL AND decided_by IS NOT NULL))
);

CREATE INDEX advance_approval_entries_month_order ON advance_approval_entries (month, id);
CREATE INDEX advance_approval_entries_month_status ON advance_approval_entries (month, status);
