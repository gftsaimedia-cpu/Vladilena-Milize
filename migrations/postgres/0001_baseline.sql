CREATE FUNCTION audit_log_no_delete_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION '%', 'audit_log chỉ được thêm dòng' USING ERRCODE = 'integrity_constraint_violation';
  RETURN OLD;
END $$;
CREATE TRIGGER audit_log_no_delete BEFORE DELETE ON audit_log FOR EACH ROW EXECUTE FUNCTION audit_log_no_delete_fn();

