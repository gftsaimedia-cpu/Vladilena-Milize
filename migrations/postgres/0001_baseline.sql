-- Lược đồ gốc PostgreSQL (dịch từ lược đồ SQLite cuối cùng của lib/db.js ở G2). Số liệu tiền dùng BIGINT; id dùng IDENTITY.
-- Trigger chỉ-thêm-dòng / khoá bản chụp viết lại bằng PL/pgSQL, giữ nguyên câu báo lỗi.

CREATE TABLE advance_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL CHECK (length(username) > 0),
    month TEXT NOT NULL CHECK (month ~ '^[0-9]{4}-[0-1][0-9]$'),
    amount BIGINT NOT NULL CHECK (amount > 0),     -- số xin, VND đồng nguyên
    cap BIGINT NOT NULL CHECK (cap >= 0),             -- mức tối đa của tháng lúc gửi
    note TEXT,                                                                      -- lời nhắn của nhân sự (không bắt buộc)
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected','cancelled')),
    granted BIGINT CHECK (granted IS NULL OR (granted > 0)),  -- số được duyệt (có thể thấp hơn số xin)
    rev BIGINT NOT NULL DEFAULT 1,
    created_at TEXT NOT NULL,
    decided_by TEXT, decided_at TEXT, decision_note TEXT,
    cancelled_by TEXT, cancelled_at TEXT
  );

CREATE TABLE ai_finding_actions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    finding_id TEXT NOT NULL, digest TEXT NOT NULL,      -- id ổn định và băm bằng chứng của phát hiện
    month TEXT NOT NULL, rule_id TEXT NOT NULL,
    action TEXT NOT NULL CHECK (action IN ('dismiss','restore')),
    by TEXT NOT NULL, at TEXT NOT NULL, note TEXT NOT NULL CHECK (length(note) BETWEEN 10 AND 300)
  );

CREATE TABLE ai_review_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    month TEXT NOT NULL, run_id BIGINT,                   -- payroll_runs.id nếu chạy sau 'calculate'
    rules_json TEXT NOT NULL, thresholds_hash TEXT NOT NULL, params_hash TEXT NOT NULL,
    findings_total BIGINT, summary_json TEXT,             -- chỉ số đếm theo mức và luật; KHÔNG tên, KHÔNG tiền
    by TEXT NOT NULL, at TEXT NOT NULL
  );

CREATE TABLE attendance_days (    -- giờ chấm công gửi Admin, tách khỏi lịch ước tính
    username   TEXT NOT NULL,
    date       TEXT NOT NULL,
    entry_json TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    PRIMARY KEY (username, date)
  );

CREATE TABLE attendance_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username TEXT NOT NULL, date TEXT NOT NULL,
    state TEXT NOT NULL CHECK(state IN ('open','closed')), entry_json TEXT NOT NULL,
    version BIGINT NOT NULL DEFAULT 1, legacy_key TEXT UNIQUE, created_at TEXT NOT NULL, updated_at TEXT NOT NULL);

CREATE TABLE audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at TEXT NOT NULL,                       -- ISO UTC
    actor TEXT NOT NULL,                    -- username hoặc 'system'
    actor_roles TEXT,                       -- vai trò lúc làm (mảng JSON)
    action TEXT NOT NULL,                   -- 'param.set', 'request.decide', 'slip.override', 'period.lock'...
    entity_kind TEXT NOT NULL, entity_id TEXT NOT NULL,
    subject TEXT,                           -- người bị tác động
    month TEXT,
    before_json TEXT, after_json TEXT,      -- chỉ qua danh sách trường cho phép của lib/audit.js, không bao giờ chứa bí mật
    reason TEXT,
    sensitivity TEXT NOT NULL DEFAULT 'normal' CHECK (sensitivity IN ('normal','pay','pii')),
    request_id TEXT,                        -- mã yêu cầu HTTP, để nối nhiều dòng của một thao tác
    prev_hash TEXT NOT NULL, hash TEXT NOT NULL
  , subject_uuid TEXT, actor_uuid TEXT);

CREATE TABLE benefit_types (
