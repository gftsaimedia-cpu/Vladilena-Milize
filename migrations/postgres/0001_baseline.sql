CREATE FUNCTION staff_roles_guard_update_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.username IS DISTINCT FROM OLD.username OR NEW.role IS DISTINCT FROM OLD.role OR NEW.granted_by IS DISTINCT FROM OLD.granted_by
      OR NEW.granted_at IS DISTINCT FROM OLD.granted_at OR OLD.revoked_at IS NOT NULL OR NEW.revoked_at IS NULL THEN
    RAISE EXCEPTION '%', 'staff_roles chỉ được đặt revoked_at một lần' USING ERRCODE = 'integrity_constraint_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER staff_roles_guard_update BEFORE UPDATE ON staff_roles FOR EACH ROW EXECUTE FUNCTION staff_roles_guard_update_fn();

