CREATE TABLE kpi_scores (           -- điểm 5 thành phần KPI, mỗi người mỗi tháng một dòng; null = chưa nhập
    username    TEXT NOT NULL,
    month       TEXT NOT NULL,                       -- 'YYYY-MM'
    wework BIGINT CHECK (wework IS NULL OR (wework >= 0 AND wework <= 10000)),                           -- Base Wework (điểm × 100)
    user_score BIGINT CHECK (user_score IS NULL OR (user_score >= 0 AND user_score <= 10000)),                       -- người dùng
    peer BIGINT CHECK (peer IS NULL OR (peer >= 0 AND peer <= 10000)),                             -- đồng nghiệp
