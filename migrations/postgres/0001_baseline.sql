  RAISE EXCEPTION '%', 'staff_roles chỉ được thu hồi (revoked_at), không xoá' USING ERRCODE = 'integrity_constraint_violation';
  RETURN OLD;
END $$;
CREATE TRIGGER staff_roles_no_delete BEFORE DELETE ON staff_roles FOR EACH ROW EXECUTE FUNCTION staff_roles_no_delete_fn();

