CREATE FUNCTION advance_requests_guard_update_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.username IS DISTINCT FROM OLD.username OR NEW.month IS DISTINCT FROM OLD.month OR NEW.amount IS DISTINCT FROM OLD.amount
      OR NEW.created_at IS DISTINCT FROM OLD.created_at
      OR OLD.status IN ('rejected','cancelled') OR (OLD.status = 'approved' AND NEW.status NOT IN ('approved','cancelled')) THEN
    RAISE EXCEPTION '%', 'advance_requests: không đổi người, tháng, số xin; yêu cầu đã từ chối hoặc huỷ là trạng thái cuối' USING ERRCODE = 'integrity_constraint_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER advance_requests_guard_update BEFORE UPDATE ON advance_requests FOR EACH ROW EXECUTE FUNCTION advance_requests_guard_update_fn();

