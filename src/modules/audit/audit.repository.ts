// Ghi nhật ký kiểm toán (audit_log). Mọi hàm nhận executor do người gọi truyền vào,
// để dòng nhật ký nằm cùng transaction với thao tác nghiệp vụ.
import { Injectable } from '@nestjs/common';
import type { Kysely } from 'kysely';
import type { DB } from '../../database/schema';
import type { DatabaseTransaction } from '../../database/transaction';
import type { StoredAuditRow } from './domain/audit-chain';

export type AuditExecutor = Kysely<DB> | DatabaseTransaction;

@Injectable()
export class AuditRepository {
  /** Dòng cuối của chuỗi (id lớn nhất), hoặc undefined nếu bảng trống. */
  async last(db: AuditExecutor): Promise<{ id: number; hash: string } | undefined> {
    return await db.selectFrom('audit_log').select(['id', 'hash']).orderBy('id', 'desc').limit(1).executeTakeFirst();
  }

  /** Ghi đủ 18 cột, kể cả id (cột GENERATED BY DEFAULT nhận id tường minh). */
  async insert(db: AuditExecutor, row: StoredAuditRow): Promise<void> {
    await db
      .insertInto('audit_log')
      .values({
        id: row.id,
        prev_hash: row.prev_hash,
        at: row.at,
        actor: row.actor,
        actor_uuid: row.actor_uuid,
        actor_roles: row.actor_roles,
        action: row.action,
        entity_kind: row.entity_kind,
        entity_id: row.entity_id,
        subject: row.subject,
        subject_uuid: row.subject_uuid,
        month: row.month,
        before_json: row.before_json,
        after_json: row.after_json,
        reason: row.reason,
        sensitivity: row.sensitivity,
        request_id: row.request_id,
        hash: row.hash
      })
      .execute();
  }
}
